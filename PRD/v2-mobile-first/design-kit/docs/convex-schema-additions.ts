// packages/convex/schema.ts: proposed additions. Same conventions as the repo.
import { defineTable } from "convex/server";
import { v } from "convex/values";

export const proposedTables = {
  devices: defineTable({
    userId: v.id("users"),
    // ios | android | web
    kind: v.union(v.literal("ios"), v.literal("android"), v.literal("web")),
    // Human label derived from the user agent, e.g. "Chrome on Mac".
    label: v.string(),
    // ML-KEM-768 public key of the device (for handoffs to it).
    devicePublicKey: v.optional(v.string()),
    // True when the user ticked "Trust this browser".
    trusted: v.boolean(),
    lastSeenAt: v.number(),
    revokedAt: v.optional(v.number()),
    createdAt: v.number(),
  }).index("by_user", ["userId"]),

  pairing_sessions: defineTable({
    // Set when the phone approves.
    userId: v.optional(v.id("users")),
    // Ephemeral ML-KEM-768 public key generated by the new browser / device.
    browserPublicKey: v.string(),
    userAgent: v.string(),
    approxLocation: v.optional(v.string()),
    status: v.union(v.literal("waiting"), v.literal("approved"), v.literal("consumed"), v.literal("expired"), v.literal("rejected")),
    // ML-KEM + AES-GCM envelope of the MasterKey, read once.
    envelope: v.optional(v.string()),
    // ML-DSA-65 signature by the approving device.
    approvalSignature: v.optional(v.string()),
    // SHA-256 of the one-time login token; the token itself is never stored.
    loginTokenHash: v.optional(v.string()),
    expiresAt: v.number(),
    createdAt: v.number(),
  }).index("by_status_expiry", ["status", "expiresAt"]),

  cloud_backup_envelopes: defineTable({
    userId: v.id("users"),
    provider: v.union(v.literal("icloud"), v.literal("google")),
    // AES-GCM(CBK, RootKey). CBK lives only in iCloud Keychain / Google Block Store.
    envelope: v.string(),
    createdAt: v.number(),
    lastRestoredAt: v.optional(v.number()),
  }).index("by_user", ["userId"]),

  recovery_requests: defineTable({
    userId: v.id("users"),
    // ML-KEM-768 public key of the new device.
    newDevicePublicKey: v.string(),
    status: v.union(v.literal("pending"), v.literal("approved_1"), v.literal("approved_2"), v.literal("released"), v.literal("rotated"), v.literal("cancelled"), v.literal("rejected"), v.literal("expired")),
    // createdAt + 48 h.
    windowEndsAt: v.number(),
    scheduledReleaseId: v.optional(v.id("_scheduled_functions")),
    cancelledAt: v.optional(v.number()),
    createdAt: v.number(),
  }).index("by_user_status", ["userId", "status"]),

  recovery_approvals: defineTable({
    requestId: v.id("recovery_requests"),
    contactId: v.id("trusted_contacts"),
    decision: v.union(v.literal("approve"), v.literal("reject")),
    // Recovery Secret share re-wrapped to the new device key.
    wrappedShareForDevice: v.optional(v.string()),
    // ML-DSA-65 over (requestId, decision, envelope hash).
    signature: v.string(),
    createdAt: v.number(),
  }).index("by_request_contact", ["requestId", "contactId"]),

  recovery_secret_shares: defineTable({
    userId: v.id("users"),
    contactId: v.id("trusted_contacts"),
    generation: v.number(),
    // ML-KEM envelope of one Shamir share of the Recovery Secret.
    wrappedShare: v.string(),
  }).index("by_user_generation", ["userId", "generation"]),

  social_envelopes: defineTable({
    userId: v.id("users"),
    generation: v.number(),
    // AES-GCM(HKDF(RS || G), MasterKey).
    envelope: v.string(),
  }).index("by_user", ["userId"]),

  gate_keys: defineTable({
    userId: v.id("users"),
    generation: v.number(),
    // Encrypted by an external KMS; only a "use node" action can decrypt it.
    kmsCiphertext: v.string(),
  }).index("by_user_generation", ["userId", "generation"]),
};

