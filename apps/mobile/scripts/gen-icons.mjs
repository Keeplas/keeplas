#!/usr/bin/env node
// Generates src/components/icon-paths.generated.ts from the 58 design-kit
// icons (PRD/v2-mobile-first/design-kit/svg/icons, 24 px, stroke =
// currentColor). Each kit icon is a single <path>; we keep its `d` and its
// stroke width so <Icon> can draw it with react-native-svg in any colour.
// Run: pnpm --filter @keeplas/mobile gen:icons
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "../../PRD/v2-mobile-first/design-kit/svg/icons");
const target = join(root, "src/components/icon-paths.generated.ts");

const entries = readdirSync(source)
  .filter((file) => file.endsWith(".svg"))
  .sort()
  .map((file) => {
    const svg = readFileSync(join(source, file), "utf8");
    const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)];
    if (paths.length !== 1) throw new Error(`${file}: expected one <path>`);
    const stroke = svg.match(/stroke-width="([\d.]+)"/)?.[1] ?? "1.75";
    const name = file.replace(/\.svg$/, "");
    return `  "${name}": { d: ${JSON.stringify(paths[0][1])}, strokeWidth: ${stroke} },`;
  });

writeFileSync(
  target,
  `// Generated by scripts/gen-icons.mjs from the design-kit icons. Do not edit.\n` +
    `export const ICON_PATHS = {\n${entries.join("\n")}\n} as const;\n\n` +
    `export type IconName = keyof typeof ICON_PATHS;\n`,
);
console.log(`Wrote ${entries.length} icons to ${target}`);
