#!/usr/bin/env node
// Generates src/components/illustrations.generated.tsx from the animated
// website illustrations (copied verbatim from keeplas-website
// apps/web/src/assets/illustrations into assets/illustrations).
//
// The website animates them with CSS keyframes inside the SVG (`.ill-sway`,
// `.ill-glow`, `.ill-shimmer`, `.ill-drift`), which react-native-svg ignores.
// This script turns each SVG into a react-native-svg component and wraps
// every `.ill-*` group in <Ambient> with the same duration, delay and pivot,
// so both platforms share one source and the same motion.
// Run: pnpm --filter @keeplas/mobile gen:illustrations
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "src/components/illustrations.generated.tsx");

// Component name → source file (website name in the comment).
const SOURCES = {
  Lake: "assets/illustrations/lake.svg", // desktop-landscape.svg
  LakeNight: "assets/illustrations/lake-night.svg", // desktop-landscape-night.svg
};

const TAGS = {
  g: "G",
  path: "Path",
  rect: "Rect",
  defs: "Defs",
  clipPath: "ClipPath",
  linearGradient: "LinearGradient",
  radialGradient: "RadialGradient",
  stop: "Stop",
};

const camel = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const seconds = (value) => Math.abs(parseFloat(value ?? "0"));

function parseAttrs(source) {
  return Object.fromEntries(
    [...source.matchAll(/([\w:-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]),
  );
}

function parseStyle(style = "") {
  return Object.fromEntries(
    style
      .split(";")
      .filter(Boolean)
      .map((rule) => rule.split(":").map((part) => part.trim())),
  );
}

const jsxAttrs = (attrs) =>
  Object.entries(attrs)
    .map(([key, value]) => ` ${camel(key)}=${JSON.stringify(value)}`)
    .join("");

/** `.ill-glow` scales around its disc: translate of the child + radius. */
function glowCentre(svg, from) {
  const m = svg
    .slice(from)
    .match(
      /^<g transform="matrix\(1 0 0 1 ([\d.-]+) ([\d.-]+)\)"><path d="M([\d.]+) ([\d.]+)/,
    );
  if (!m) throw new Error("ill-glow: expected a translated disc path");
  const [tx, ty, r] = [m[1], m[2], m[3]].map(Number);
  return [tx + r, ty + r];
}

function ambient(kind, attrs, svg, from) {
  const style = parseStyle(attrs.style);
  const props = [`kind="${kind}"`];
  if (kind === "sway") {
    const origin = style["transform-origin"].replace(/px/g, "").split(/\s+/);
    props.push(`origin={[${origin.join(", ")}]}`);
  }
  if (kind === "glow") props.push(`origin={[${glowCentre(svg, from)}]}`);
  // Defaults come from the website's `.ill-*` rules.
  const fallback = { sway: 3.5, glow: 2, shimmer: 2, drift: 7 }[kind];
  props.push(
    `duration={${seconds(style["animation-duration"]) || fallback}}`,
    `delay={${seconds(style["animation-delay"])}}`,
    "play={play}",
  );
  return `<Ambient ${props.join(" ")}>`;
}

function convert(name, file) {
  const svg = readFileSync(join(root, file), "utf8")
    .replace(/<style>[\s\S]*?<\/style>/, "")
    .replace(/<g id="play"\/>/, "");
  const open = svg.match(/^<svg([^>]*)>/);
  const { viewBox } = parseAttrs(open[1]);
  const stack = [];
  let body = "";
  const tag = /<(\/?)([\w]+)([^>]*?)(\/?)>/g;
  tag.lastIndex = open[0].length;
  for (let m; (m = tag.exec(svg));) {
    const [, closing, element, rawAttrs, selfClosing] = m;
    if (element === "svg") break;
    const component = TAGS[element];
    if (!component) throw new Error(`${file}: unsupported <${element}>`);
    if (closing) {
      body += `</${stack.pop()}>`;
      continue;
    }
    const attrs = parseAttrs(rawAttrs);
    const kind = attrs.class?.match(/^ill-(\w+)$/)?.[1];
    if (kind) {
      body += ambient(kind, attrs, svg, tag.lastIndex);
      if (!selfClosing) stack.push("Ambient");
      continue;
    }
    if (attrs.class || attrs.style) throw new Error(`${file}: stray CSS`);
    body += `<${component}${jsxAttrs(attrs)}${selfClosing ? " />" : ">"}`;
    if (!selfClosing) stack.push(component);
  }
  return (
    `export function ${name}(props: SvgProps) {\n` +
    `  const play = usePlayAmbient();\n` +
    `  return (\n<Svg viewBox="${viewBox}" fill="none" {...props}>${body}</Svg>\n  );\n}\n`
  );
}

writeFileSync(
  target,
  `// Generated by scripts/gen-illustrations.mjs from the website SVGs. Do not edit.\n` +
    `import Svg, {\n  ${[...new Set(Object.values(TAGS))].sort().join(",\n  ")},\n  type SvgProps,\n} from "react-native-svg";\n\n` +
    `import { Ambient, usePlayAmbient } from "./ambient";\n\n` +
    Object.entries(SOURCES)
      .map(([name, file]) => convert(name, file))
      .join("\n"),
);
console.log(`Wrote ${Object.keys(SOURCES).length} illustrations to ${target}`);
